// 构建时同步脚本：按 src/config/regionBlockConfig.ts 的 REGION_BLOCK_ROUTES
// 生成/清理 functions/ 下的 EdgeOne 边缘函数文件
// 由 package.json 的 build 命令自动执行，无需手动维护 functions 目录

import { readFileSync, writeFileSync, readdirSync, statSync, rmSync, mkdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONFIG_PATH = join(ROOT, "src/config/regionBlockConfig.ts");
const FUNCTIONS_DIR = join(ROOT, "functions");
const MARKER = "// [auto-generated by scripts/sync-region-functions.mjs]";

const source = readFileSync(CONFIG_PATH, "utf-8");

// 从配置中提取开关为 true 的路由与拦截国家码（保持配置文件为唯一事实来源）
const routes = [...source.matchAll(/"([^"]+)"\s*:\s*true/g)].map((m) => m[1]);
const codesMatch = source.match(/REGION_BLOCKED_COUNTRY_CODES\s*=\s*\[([^\]]*)\]/);
const countryCodes = codesMatch
	? [...codesMatch[1].matchAll(/"([^"]+)"/g)].map((m) => m[1])
	: ["CN"];

// 递归清理此前生成的函数文件（带标记头），并删除因此变空的目录
function cleanGenerated(dir) {
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) {
			cleanGenerated(full);
			if (readdirSync(full).length === 0) rmSync(full, { recursive: true });
		} else if (entry.endsWith(".js")) {
			const head = readFileSync(full, "utf-8").slice(0, 200);
			if (head.includes(MARKER)) rmSync(full);
		}
	}
}

// 路由转函数文件路径："/life/guestbook/" → functions/life/guestbook.js
function routeToFile(route) {
	return join(FUNCTIONS_DIR, route.replace(/^\/|\/$/g, "") + ".js");
}

if (statSync(FUNCTIONS_DIR, { throwIfNoEntry: false })) cleanGenerated(FUNCTIONS_DIR);

const template = (route) => `${MARKER}
// EdgeOne Pages 边缘函数：按客户端地理位置拦截页面
// 由 scripts/sync-region-functions.mjs 依据 src/config/regionBlockConfig.ts 生成，
// 请勿直接编辑本文件——修改 regionBlockConfig.ts 后重新构建即可

const BLOCKED_COUNTRY_CODES = ${JSON.stringify(countryCodes)};
const ROUTE = "${route}";

export async function onRequest(context) {
	const geo = context.request.eo && context.request.eo.geo;
	const code = String(
		(geo && (geo.countrycode || geo.countryCode)) || "",
	).toUpperCase();
	if (BLOCKED_COUNTRY_CODES.indexOf(code) >= 0) {
		return new Response("404 Not Found", { status: 404 });
	}
	// 非拦截地区：fetch(request) 访问 EdgeOne 节点缓存/回源获取 Pages 静态资源
	// （HOST 与客户端请求一致，符合回源条件；CLI 本地调试不支持该特性，线上可用）
	return fetch(context.request);
}
`;

for (const route of routes) {
	const file = routeToFile(route);
	mkdirSync(dirname(file), { recursive: true });
	writeFileSync(file, template(route));
}

console.log(
	`[sync-region-functions] 已同步 ${routes.length} 个屏蔽路由: ${routes.join(", ") || "(无)"}`,
);
